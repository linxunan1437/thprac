"""Embed immutable checkpoint and reviewed phase CSVs in one translation unit."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
out='// AUTO-GENERATED by docs/logger/tools/gen_th07_checkpoints.py; DO NOT EDIT.\nnamespace THPrac { namespace TH07 {\n'
for filename,symbol,delimiter in [('th07_checkpoints.csv','kTh07CheckpointsCsv','TH07CSV'),('th07_boss_phases.csv','kTh07BossPhasesCsv','TH07PHASE')]:
    body=(ROOT/'docs/logger'/filename).read_bytes().decode('utf-8-sig')
    assert ')'+delimiter+'"' not in body
    out+=f'extern const char {symbol}[] = R"{delimiter}('+body+f'){delimiter}";\n'
out+='} }\n'
target=ROOT/'thprac/src/thprac/thprac_th07_checkpoints_gen.cpp'
data=out.encode('utf-8')
if not target.exists() or target.read_bytes()!=data: target.write_bytes(data)
assert target.read_bytes()==data
for filename,symbol,delimiter in [('th07_checkpoints.csv','kTh07CheckpointsCsv','TH07CSV'),('th07_boss_phases.csv','kTh07BossPhasesCsv','TH07PHASE')]:
    embedded=out.split('R"'+delimiter+'(',1)[1].split(')'+delimiter+'"',1)[0]
    assert embedded.encode('utf-8')==(ROOT/'docs/logger'/filename).read_bytes().removeprefix(b'\xef\xbb\xbf')
print('TH07 generated CSVs round-trip byte-identically; deterministic output')
