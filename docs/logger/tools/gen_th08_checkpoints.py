#!/usr/bin/env python3
"""Embed TH08 checkpoints and reviewed L/Extra phase sub aliases. --check is read-only."""
import argparse
import csv
import io
from pathlib import Path
from investigate_th08_boss import run, FILES

ROOT=Path(__file__).resolve().parents[3]
ALIASES={
    'ST2':[(51,'ST2 BOSS5')], 'ST4A':[(45,'ST4A BOSS9')],
    'ST4B':[(61,'ST4B BOSS9')], 'ST6A':[(72,'ST6A BOSS9')],
    'ST6B':[(70,'ST6B BOSS9')],
    'ST7':[(55,'ST7 MID2'),(59,'ST7 MID3'),(82,'ST7 END_S9'),(83,'ST7 END_S10')],
}

def generate(materials):
    rows=run(materials)
    body=(ROOT/'docs/logger/th08_checkpoints.csv').read_bytes().decode('utf-8-sig')
    phases=io.StringIO();writer=csv.writer(phases,lineterminator='\n')
    writer.writerow(['stage','sub','record'])
    seen=set()
    for row in rows:
        key=(row['stage'],int(row['candidate_sub'][3:]))
        assert key not in seen;seen.add(key)
        writer.writerow([*key,row['record']])
    # Every alias must synchronously call the candidate it represents.
    import re
    for stage,aliases in ALIASES.items():
        decl=(materials/'ecl_dump/th08'/('ecldata'+FILES[stage]+'.decl')).read_text(encoding='cp932',errors='replace')
        for sub,record in aliases:
            target=next(int(r['candidate_sub'][3:]) for r in rows if r['record']==record)
            block=re.search(r'sub Sub'+str(sub)+r'\(\)\s*\{(.*?)\n\}',decl,re.S)[1]
            assert f'call({target});' in block,(stage,sub,target)
            assert (stage,sub) not in seen;seen.add((stage,sub))
            writer.writerow([stage,sub,record])
    out='// AUTO-GENERATED by docs/logger/tools/gen_th08_checkpoints.py. DO NOT EDIT.\n'
    out+='// Checkpoints + L/Extra phase whitelist (104 records, 9 synchronous wrapper aliases).\n'
    out+='namespace THPrac { namespace TH08 {\n'
    for symbol,delim,text in [('kTh08CheckpointsCsv','TH08CSV',body),('kTh08BossPhasesCsv','TH08BOSS',phases.getvalue())]:
        assert ')'+delim+'"' not in text
        out+=f'extern const char {symbol}[] = R"{delim}({text}){delim}";\n'
    return (out+'} }\n').encode('utf-8')

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true')
    ap.add_argument('--materials',type=Path,default=ROOT.parent/'reasm/exes');a=ap.parse_args()
    out=ROOT/'thprac/src/thprac/thprac_th08_checkpoints_gen.cpp';data=generate(a.materials)
    if a.check:assert out.read_bytes()==data,'generated output is stale'
    elif not out.exists() or out.read_bytes()!=data:out.write_bytes(data)
    print('TH08 generated CSV round-trip and 104 records + 9 direct-call aliases verified')

if __name__=='__main__':main()
