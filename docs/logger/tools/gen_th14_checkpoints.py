#!/usr/bin/env python3
"""Generate thprac/src/thprac/thprac_th14_checkpoints_gen.cpp from the checkpoint CSV.

The generated translation unit embeds docs/logger/th14_checkpoints.csv verbatim as a
C++ raw string literal so that the runtime never needs to touch the filesystem.

Idempotent: re-running on an unchanged CSV rewrites byte-identical output.

Usage (from anywhere):
    python docs/logger/tools/gen_th14_checkpoints.py
"""

import pathlib
import sys

# docs/logger/tools/gen_th14_checkpoints.py -> repo root
REPO_ROOT = pathlib.Path(__file__).resolve().parents[3]
CSV_PATH = REPO_ROOT / "docs" / "logger" / "th14_checkpoints.csv"
OUT_PATH = REPO_ROOT / "thprac" / "src" / "thprac" / "thprac_th14_checkpoints_gen.cpp"

# Raw string literal delimiter. The CSV body must not contain ")TH14CSV\"".
RAW_DELIM = "TH14CSV"

BANNER = (
    "// AUTO-GENERATED by docs/logger/tools/gen_th14_checkpoints.py -- DO NOT EDIT BY HAND.\n"
    "// Source: docs/logger/th14_checkpoints.csv\n"
    "// Regenerate with: python docs/logger/tools/gen_th14_checkpoints.py\n"
    "\n"
)


def main() -> int:
    if not CSV_PATH.is_file():
        print(f"error: csv not found: {CSV_PATH}", file=sys.stderr)
        return 1

    raw = CSV_PATH.read_bytes()
    if raw.startswith(b"\xef\xbb\xbf"):  # strip UTF-8 BOM if a future edit adds one
        raw = raw[3:]
    try:
        body = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        print(f"error: csv is not valid utf-8: {exc}", file=sys.stderr)
        return 1

    terminator = ')' + RAW_DELIM + '"'
    if terminator in body:
        print(f"error: csv body contains raw-string terminator {terminator!r}", file=sys.stderr)
        return 1

    out = (
        BANNER
        + "namespace THPrac {\n"
        + "namespace TH14 {\n"
        + "\n"
        + "    extern const char kTh14CheckpointsCsv[] = R\""
        + RAW_DELIM
        + "("
        + body
        + terminator
        + ";\n"
        + "\n"
        + "}\n"
        + "}\n"
    )
    out_bytes = out.encode("utf-8")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    changed = (not OUT_PATH.is_file()) or OUT_PATH.read_bytes() != out_bytes
    if changed:
        OUT_PATH.write_bytes(out_bytes)

    # Self-check: the embedded body must be byte-identical to the CSV.
    written = OUT_PATH.read_bytes().decode("utf-8")
    marker = "R\"" + RAW_DELIM + "("
    start = written.index(marker) + len(marker)
    end = written.index(terminator, start)
    assert written[start:end] == body, "round-trip mismatch"

    print(f"{'wrote' if changed else 'unchanged'} {OUT_PATH.relative_to(REPO_ROOT)}")
    print(f"  csv bytes: {len(raw)}  embedded bytes: {len(written[start:end].encode('utf-8'))}")
    print("  self-check: embedded body is byte-identical to the csv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
